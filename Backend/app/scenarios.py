CORE_SCENARIO_IDS: tuple[str, ...] = tuple(_CORE)

SCENARIOS: dict[str, dict[str, Any]] = {**_CORE, **generate_scenarios()}


def run_scenario(scenario_id: str) -> dict[str, Any]:
    """Return simulated event data without revealing ground truth.

    The event includes "scenario_id". For the core scenarios that ID is a
    readable name such as "benign_admin", which tells a model the answer.
    Feed systems get_detector_input() instead.
    """
    if scenario_id not in SCENARIOS:
        raise ValueError(f"Unknown scenario: {scenario_id}")

    event = copy.deepcopy(SCENARIOS[scenario_id]["event"])
    event["scenario_id"] = scenario_id
    return event


def get_detector_input(scenario_id: str) -> dict[str, Any]:
    """Return the event exactly as a detector or LLM is allowed to see it.

    This has no scenario_id, so nothing in it names the scenario.
    """
    event = run_scenario(scenario_id)
    event.pop("scenario_id")
    return event


def get_ground_truth(scenario_id: str) -> dict[str, Any]:
    """Return the independently assigned labels for evaluation only."""
    if scenario_id not in SCENARIOS:
        raise ValueError(f"Unknown scenario: {scenario_id}")

    return copy.deepcopy(SCENARIOS[scenario_id]["ground_truth"])


def list_scenarios() -> list[str]:
    """List available scenario IDs (core first, then generated)."""
    return list(SCENARIOS.keys())