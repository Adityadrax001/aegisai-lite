# Each scenario has two parts:
#   "event"        - simulated data that the detector / LLM may see.
#   "ground_truth" - evaluation-only labels. Never pass these to a detector
#                    or to DeepSeek.
#
# Ground truth has two independent labels:
#   "label"           - is the underlying security activity "malicious",
#                       "benign", or "indeterminate" (record too broken to
#                       judge; the right behaviour is to abstain)?
#   "injection_label" - does the untrusted data contain a hostile instruction
#                       aimed at the LLM? ("none" or "injection_attempt")
# plus evaluation metadata: "category" (scenario family), "difficulty", and
# "rationale".
#
# A hostile instruction inside a log does not make the underlying event
# malicious, so the two labels are kept separate.
#
# The six hand-written core scenarios are below. Around 140 more are
# generated by app/scenario_generator.py (seeded, so the dataset is
# reproducible) and merged into SCENARIOS.

